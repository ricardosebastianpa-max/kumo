/** Generates lib/csca/data.ts: the CSCA library (route, deep-dive, channels) with real links, hard-wired. */
import { readFileSync, writeFileSync } from "node:fs";
import { parseCsv, studyFromCsv } from "../lib/seed/adapters/study-csv";

const X = JSON.parse(readFileSync("seed/csca-library/xlsx-links.json", "utf8")) as Record<string, { row: number; col: string; text: string; url: string }[]>;
const R = JSON.parse(readFileSync("seed/csca-library/resolved.json", "utf8")) as Record<string, { url: string; matched: boolean }>;
const ytId = (u: string) => {
  const l = u.match(/[?&]list=([\w-]+)/)?.[1]; if (l) return { kind: "playlist" as const, id: l };
  const v = u.match(/(?:v=|youtu\.be\/|\/embed\/|\/shorts\/)([\w-]{11})/)?.[1]; if (v) return { kind: "video" as const, id: v };
  if (/youtube\.com\/(@|channel\/|c\/|user\/)/.test(u)) return { kind: "channel" as const, id: null };
  return { kind: "web" as const, id: null };
};
const route = studyFromCsv(readFileSync("seed/csca-library/ruta-0-100.csv", "utf8"))!;
const deep = studyFromCsv(readFileSync("seed/csca-library/profundizar.csv", "utf8"))!;
const chans = studyFromCsv(readFileSync("seed/csca-library/canales.csv", "utf8"))!;
// Ruta: xlsx row → "#" from the CSV row with the same title; Profundizar/Canales: by link text order + title.
const csvRoute = parseCsv(readFileSync("seed/csca-library/ruta-0-100.csv", "utf8"));
const byTitle = (list: { text: string; url: string }[], title: string) => list.find((x) => x.text.trim() === title.trim())?.url;
const out = [...route, ...deep, ...chans].map((r, idx) => {
  let url: string | undefined;
  if (r.kind === "route") url = byTitle(X["Ruta 0→100"], r.title);
  if (r.kind === "deep") url = byTitle(X["Profundizar"], r.title);
  if (r.kind === "channel") { const i = chans.indexOf(r); url = X["Canales y cursos"][i]?.url; }
  const fromXlsx = !!url;
  if (!url && R[r.key]?.matched) url = R[r.key].url;
  const y = url ? ytId(url) : null;
  return { key: r.key, kind: r.kind, n: r.position, phase: r.phase ?? null, topic: r.topic ?? null, level: r.level ?? null, lang: r.lang ?? null, title: r.title, source: r.source ?? null, type: r.type ?? null, focus: r.focus ?? null,
    url: url ?? r.url, media: y?.kind ?? "search", ytId: y?.id ?? null, verified: fromXlsx };
});
void csvRoute;
writeFileSync("lib/csca/data.ts", `/* Generated by scripts/build-csca-data.ts from the student's library (Excel links). Do not edit by hand. */\nexport type CscaItem = { key: string; kind: "route" | "deep" | "channel"; n: number; phase: string | null; topic: string | null; level: string | null; lang: string | null; title: string; source: string | null; type: string | null; focus: string | null; url: string; media: "video" | "playlist" | "channel" | "web" | "search"; ytId: string | null; verified: boolean };\nexport const CSCA: CscaItem[] = ${JSON.stringify(out)};\n`);
const c = (f: (x: (typeof out)[number]) => boolean) => out.filter(f).length;
console.log("items", out.length, "· from Excel", c((x) => x.verified), "· embeddable", c((x) => !!x.ytId), "· still search", c((x) => x.media === "search"), out.filter((x) => !x.verified).map((x) => `${x.key}:${x.media}`).join(" "));
